def validate_chain(cfg):
    errors = []
    gens = cfg['generators']['generators']
    primary = next((r['codeName'] for r in cfg['resources']['resources'] if r.get('isPrimary')), None)
    for i in range(len(gens) - 1):
        current = gens[i]
        nxt = gens[i + 1]
        produces = [p['resource'] for p in current.get('produces', [])]
        next_costs = [c['resource'] for c in nxt.get('costResources', [])]
        conds = nxt.get('unlockConditions') or {}
        next_held = [c['resource'] for c in (conds.get('conditions') or []) if c.get('type') == 'resourceHeld']
        needed = list(dict.fromkeys(next_costs + next_held))
        for res in needed:
            if res == primary:
                continue
            if res not in produces:
                errors.append(f"{current['codeName']} does not produce {res} for {nxt['codeName']}")
    return errors


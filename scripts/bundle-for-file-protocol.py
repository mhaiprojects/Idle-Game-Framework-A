def strip_ui(content, declared_imports):
    lines = content.split('\n')
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^import\s+(\w+)\s+from\s+['\"]([^'\"]+)['\"];?\s*$", line)
        if m:
            name = m.group(1)
            if name not in declared_imports:
                out.append(f'const {name} = AFK_UI.{name};')
                declared_imports.add(name)
            i += 1
            continue
        if re.match(r"^import\s+\{", line):
            i += 1
            continue
        if line.startswith('export default'):
            comp = 'Component'
            for j in range(i + 1, min(i + 5, len(lines))):
                nm = re.search(r"name:\s*'(\w+)'", lines[j])
                if nm:
                    comp = nm.group(1)
                    break
            out.append(f'AFK_UI.{comp} = {{')
            i += 1
            continue
        out.append(line)
        i += 1
    return '\n'.join(out)

